#include "libft.h"

char	*ft_strmapi(char const *s, char (*f)(unsigned int, char))
{
	char			*str;
	size_t			s_length;
	unsigned int	i;

	i = 0;
	if (s == NULL || f == NULL)
		return (NULL);
	s_length = ft_strlen(s);
	str = malloc((s_length + 1) * sizeof(char));
	if (str == NULL)
		return (NULL);
	while (s[i] != '\0')
	{
		str[i] = f(i, s[i]);
		i++;
	}
	str[i] = '\0';
	return (str);
}
